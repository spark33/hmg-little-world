import {chromium} from '@playwright/test';
const launch={executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']};
const browser=await chromium.launch(launch);
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://localhost:5174');await page.waitForTimeout(2200);
await page.screenshot({path:'../artifacts/world-initial.png'});
await page.getByRole('button',{name:'Demo settings'}).click();
await page.getByRole('button',{name:'Switch to evening'}).click();
await page.getByRole('button',{name:'Close panel'}).click();await page.waitForTimeout(1800);
await page.screenshot({path:'../artifacts/world-evening.png'});
if(errors.length)throw new Error(JSON.stringify(errors));
await page.close();
const failed=await browser.newPage({viewport:{width:1440,height:900}});
await failed.addInitScript(()=>{const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(type==='webgl'||type==='webgl2'||type==='experimental-webgl')return null;return get.call(this,type,...args)}});
await failed.goto('http://localhost:5174');await failed.getByText('A little pause in the world').waitFor();
await failed.screenshot({path:'../artifacts/webgl-fallback.png'});
console.log('Production rendering, evening mode, CSP/console check, and WebGL failure fallback passed.');
await browser.close();
